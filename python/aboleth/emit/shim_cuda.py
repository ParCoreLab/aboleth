"""CUDA binding header for a compiled transport fragment.

The default header declares the compiled symbol and marshals a typed binding
struct. An integration may additionally request an inline body generated from
the same transport program, avoiding a device-call boundary in a fused kernel.
"""

from __future__ import annotations

import re


# The fragment ABI is scalar throughout: every pointer slot travels as a device
# address, matching the extern "C" entry points of the RDMA device library.
_ABI_TYPES = {
    "i1": "std::uint32_t",
    "i32": "std::uint32_t",
    "i64": "std::uint64_t",
}
_FIELD_TYPES = {
    "i1": "bool",
    "i32": "std::uint32_t",
    "i64": "std::uint64_t",
}


def _identifier(value: str) -> str:
    words = [
        word
        for word in re.split(r"[^A-Za-z0-9]+", value)
        if word
    ]
    result = "".join(word[:1].upper() + word[1:] for word in words)
    if not result or result[0].isdigit():
        result = f"Fragment{result}"
    return result


def emit_cuda_shim(
    *,
    name: str,
    symbol: str,
    arch: str,
    binding_signature: str,
    slots: tuple[tuple[str, str, bool], ...],
    issuer_scope: str = "cta",
    inline_body: str | None = None,
    inline_includes: tuple[str, ...] = (),
) -> str:
    """Emit the header for one fragment.

    `slots` carries (name, mlir type, is_pointer) in manifest slot order, which
    is the fragment's parameter order.
    """
    stem = _identifier(name)
    struct_name = f"{stem}Bindings"
    parameters = ",\n".join(
        f"    {_ABI_TYPES[mlir_type]} {slot}"
        for slot, mlir_type, _ in slots
    )
    fields = "\n".join(
        f"    {_FIELD_TYPES[mlir_type]} {slot};"
        + ("  // device address" if pointer else "")
        for slot, mlir_type, pointer in slots
    )
    arguments = ",\n".join(
        f"        bindings.{slot}"
        + (" ? 1u : 0u" if mlir_type == "i1" else "")
        for slot, mlir_type, _ in slots
    )
    if issuer_scope == "thread":
        invocation = (
            "// Each calling thread issues its own transfer. Call only from "
            "threads that own a logical operation."
        )
    elif issuer_scope == "cta":
        invocation = (
            "// Every thread of the calling block may call this; the transport "
            "is issued\n"
            "// once, by thread 0. Other warps of the block are not synchronized "
            "with it, so\n"
            "// __syncthreads() where they depend on the transfer."
        )
    else:
        raise ValueError(
            f"unknown fragment issuer scope {issuer_scope!r}"
        )
    includes = "\n".join(
        f'#include "{header}"'
        for header in inline_includes
    )
    if includes:
        includes = "\n" + includes
    call_body = (
        inline_body
        if inline_body is not None
        else f"""{symbol}(
{arguments});"""
    )
    return f"""#pragma once

// Aboleth transport fragment "{name}" compiled for {arch}.
//
// binding signature: {binding_signature}
//
{invocation}
//
// Link one of the artifacts that ship with this header:
//   nvcc -rdc=true -dc client.cu && nvlink client.o <fragment>.cubin
//   clang++ -x cuda -fcuda-short-ptr \\
//       -Xclang -mlink-builtin-bitcode -Xclang <fragment>.bc client.cu
// The bitcode is compiled with 32-bit shared/local pointers, so a client that
// links it must also pass -fcuda-short-ptr.
//
// Generated by aboleth.artifact; do not edit.

#include <cstdint>{includes}

namespace aboleth::generated {{

inline constexpr char k{stem}Signature[] =
    "{binding_signature}";

// Returns zero; the result exists so Triton call sites can bind the symbol.
extern "C" __device__ std::uint64_t {symbol}(
{parameters});

struct {struct_name} {{
{fields}
}};

__device__ __forceinline__ void call{stem}(
    const {struct_name}& bindings) {{
{call_body}
}}

}} // namespace aboleth::generated
"""
